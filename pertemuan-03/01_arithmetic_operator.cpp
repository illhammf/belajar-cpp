#include <iostream>
using namespace std;

int main()
{
    int a = 10;
    int b = 3;

    cout << "=== ARITHMETIC OPERATOR ===" << endl;

    cout << "Penjumlahan : " << a + b << endl;
    cout << "Pengurangan : " << a - b << endl;
    cout << "Perkalian   : " << a * b << endl;
    cout << "Pembagian   : " << a / b << endl;
    cout << "Sisa        : " << a % b << endl;

    return 0;
}