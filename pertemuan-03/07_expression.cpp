#include <iostream>
using namespace std;

int main()
{
    int a = 10;
    int b = 5;

    // Expression adalah kombinasi dari variabel, operator, dan nilai yang menghasilkan sebuah nilai
    int hasil1 = a + b;
    int hasil2 = (a + b) * 2;
    int hasil3 = a * b + 10;

    cout << "Hasil 1 : " << hasil1 << endl;
    cout << "Hasil 2 : " << hasil2 << endl;
    cout << "Hasil 3 : " << hasil3 << endl;

    return 0;
}