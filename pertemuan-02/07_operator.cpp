#include <iostream>
using namespace std;

int main()
{
    int a = 10; // deklarasi dan inisialisasi variabel a dengan tipe data integer
    int b = 3; // deklarasi dan inisialisasi variabel b dengan tipe data integer

    cout << "Penjumlahan : " << a + b << endl;
    cout << "Pengurangan : " << a - b << endl;
    cout << "Perkalian   : " << a * b << endl;
    cout << "Pembagian   : " << a / b << endl;
    cout << "Sisa        : " << a % b << endl;

    return 0;
}