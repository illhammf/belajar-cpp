#include <iostream>
using namespace std;

int main()
{
    // Perulangan for digunakan untuk melakukan perulangan dengan jumlah yang telah ditentukan
    // Memakai decrement, perulangan akan dilakukan dari angka 5 hingga 1
    for (int i = 5; i >= 1; i--)
    {
        cout << i << endl;
    }

    return 0;
}