#include <iostream>

int main()
{
    int umur = 20; // Mendeklarasikan variabel umur dengan tipe data integer dan menginisialisasinya dengan nilai 20

    std::cout << "Umur saya: " << umur << std::endl;

    umur = 21; // Mengubah nilai variabel umur menjadi 21

    std::cout << "Umur saya sekarang: " << umur << std::endl;

    return 0;
}